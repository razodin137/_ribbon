#!/usr/bin/env python3
"""
Embed the browser assets into ribbon.py.

    python3 build.py

Run this after editing bar.js, bar.css, ribbon.js, card.js, card.css, or
markdown.css. The embedded copy makes ribbon.py self-contained: copy that one
file anywhere and it still serves the bar.

While working on the bar, skip the build and run:

    python3 ribbon.py --dev

With --dev, ribbon.py reads the files beside it, so each reload picks up your
edits. Check that the release copy is current with:

    python3 build.py --check
"""

from __future__ import annotations

import argparse
import base64
import zlib
from pathlib import Path

APP_DIR = Path(__file__).resolve().parent
TARGET = APP_DIR / "ribbon.py"
START = "# --- embedded assets: generated by build.py; do not edit ---"
END = "# --- end embedded assets ---"
ASSETS = ("bar.css", "bar.js", "card.css", "card.js", "markdown.css", "ribbon.js")
WRAP = 76


def embedded_block() -> str:
    lines = [START, "_EMBEDDED_ASSETS_B64: dict[str, str] = {"]
    for name in ASSETS:
        data = (APP_DIR / name).read_bytes()
        packed = zlib.compress(data, 9)
        encoded = base64.b64encode(packed).decode("ascii")
        lines.append(f'    # {name}: {len(data)} bytes -> {len(packed)} compressed')
        lines.append(f'    "{name}": (')
        for start in range(0, len(encoded), WRAP):
            lines.append(f'        "{encoded[start : start + WRAP]}"')
        lines.append("    ),")
    lines.append("}")
    lines.append(END)
    return "\n".join(lines)


def split_source(source: str) -> tuple[str, str]:
    try:
        start = source.index(START)
        end = source.index(END, start) + len(END)
    except ValueError:
        raise SystemExit(f"{TARGET.name} is missing the embedded asset markers")
    return source[:start], source[end:]


def main() -> None:
    parser = argparse.ArgumentParser(description="Embed Ribbon's assets in ribbon.py.")
    parser.add_argument(
        "--check",
        action="store_true",
        help="only check whether the embedded copies are current",
    )
    args = parser.parse_args()

    missing = [name for name in ASSETS if not (APP_DIR / name).is_file()]
    if missing:
        raise SystemExit("missing asset files: " + ", ".join(missing))

    source = TARGET.read_text(encoding="utf-8")
    head, tail = split_source(source)
    fresh = embedded_block()
    current = source[len(head) : len(source) - len(tail)]

    if current == fresh:
        print("  embedded assets are current")
        return

    if args.check:
        raise SystemExit("  embedded assets are stale; run python3 build.py")

    TARGET.write_text(head + fresh + tail, encoding="utf-8")
    print(f"  embedded {len(ASSETS)} assets in {TARGET.name}")
    for name in ASSETS:
        size = (APP_DIR / name).stat().st_size
        packed = len(zlib.compress((APP_DIR / name).read_bytes(), 9))
        print(f"  {name:<13} {size:>7} bytes -> {packed:>6} compressed")


if __name__ == "__main__":
    main()
